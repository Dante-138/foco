import { test } from 'node:test';
import assert from 'node:assert/strict';
import { execFileSync, spawnSync } from 'node:child_process';
import { mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { problemasDaMensagem, problemasDoAssunto } from '../../tools/verificar-commits.mjs';

const SCRIPT = fileURLToPath(new URL('../../tools/verificar-commits.mjs', import.meta.url));

// Repositório git descartável com três commits em linha: a base, um no padrão e um fora dele
// (o HEAD). Apagado no fim do teste.
function repositorioDeTeste(t) {
  const pasta = mkdtempSync(join(tmpdir(), 'foco-commits-'));
  t.after(() => rmSync(pasta, { recursive: true, force: true, maxRetries: 3 }));
  const git = (...argumentos) =>
    execFileSync(
      'git',
      [
        '-c',
        'user.name=Teste',
        '-c',
        'user.email=teste@example.com',
        '-c',
        'commit.gpgsign=false',
        ...argumentos,
      ],
      { cwd: pasta, encoding: 'utf8' },
    ).trim();
  const commit = (mensagem) => {
    git('commit', '--quiet', '--allow-empty', '-m', mensagem);
    return git('rev-parse', 'HEAD');
  };
  git('init', '--quiet');
  return {
    pasta,
    base: commit('chore: start'),
    bom: commit('feat: add a good one'),
    ruim: commit('Add stuff without a type'),
  };
}

// Roda o script pela linha de comando, como o gancho e o CI fazem. Sem o título de PR do ambiente.
function rodar(pasta, ...argumentos) {
  const { status, stdout, stderr } = spawnSync(process.execPath, [SCRIPT, ...argumentos], {
    cwd: pasta,
    encoding: 'utf8',
    env: { ...process.env, TITULO_PR: '', CORPO_PR: '' },
  });
  return { status, stdout, stderr };
}

// Modo --pr: não precisa de repositório, só do título e da descrição no ambiente.
function rodarPr(titulo, corpo = '') {
  const { status, stdout, stderr } = spawnSync(process.execPath, [SCRIPT, '--pr'], {
    encoding: 'utf8',
    env: { ...process.env, TITULO_PR: titulo, CORPO_PR: corpo },
  });
  return { status, stdout, stderr };
}

test('assuntos no padrão são aceitos', () => {
  const bons = [
    'feat: add Rotinas, Habitos and Tarefas tabs',
    'fix(theme): keep the dark theme as default',
    'chore: add lint, formatting, unit tests and CI',
    'refactor(store)!: change the saved data format',
    'docs: add README',
  ];
  for (const assunto of bons) assert.deepEqual(problemasDoAssunto(assunto), [], assunto);
});

test('assuntos fora do padrão são reprovados', () => {
  const ruins = [
    'Add tabs', // sem tipo
    'feature: add tabs', // tipo que não existe
    'feat add tabs', // sem dois-pontos
    'feat:add tabs', // sem espaço depois dos dois-pontos
    'feat: ', // sem descrição
    'Feat: add tabs', // tipo com maiúscula
    'feat(Tema): add tabs', // escopo com maiúscula
    'feat: add tabs.', // ponto final
    `feat: ${'a'.repeat(80)}`, // longo demais
    '',
  ];
  for (const assunto of ruins) assert.notEqual(problemasDoAssunto(assunto).length, 0, assunto);
});

test('o limite de 72 caracteres é inclusivo', () => {
  assert.deepEqual(problemasDoAssunto(`feat: ${'a'.repeat(66)}`), []);
  assert.equal(problemasDoAssunto(`feat: ${'a'.repeat(67)}`).length, 1);
});

test('mensagem com coautoria ou "gerado por" é reprovada', () => {
  const corpos = [
    'Co-Authored-By: Alguém <a@b.c>',
    'co-authored-by: alguém <a@b.c>',
    'Signed-off-by: Alguém <a@b.c>',
    'Generated with uma ferramenta',
    '\u{1F916} texto',
  ];
  for (const corpo of corpos) {
    assert.equal(problemasDaMensagem(`feat: add tabs\n\n${corpo}`).length, 1, corpo);
  }
});

test('corpo comum não é reprovado', () => {
  const mensagem = 'feat: add tabs\n\nFirst working version.\nIt was generated by hand, with care.';
  assert.deepEqual(problemasDaMensagem(mensagem), []);
});

test('confere de <base> até a <ponta> informada, e não até o HEAD', (t) => {
  const { pasta, base, bom } = repositorioDeTeste(t);

  const ateOBom = rodar(pasta, base, bom);
  assert.equal(ateOBom.status, 0, ateOBom.stderr);
  assert.match(ateOBom.stdout, /^1 mensagem\(ns\) conferida\(s\), 0 reprovada\(s\)\.$/m);

  // Sem a ponta vale o HEAD, que é o commit fora do padrão.
  const ateOHead = rodar(pasta, base);
  assert.equal(ateOHead.status, 1);
  assert.match(ateOHead.stderr, /^REPROVADO {2}\w+ Add stuff without a type$/m);
  assert.match(ateOHead.stdout, /^2 mensagem\(ns\) conferida\(s\), 1 reprovada\(s\)\.$/m);
});

test('base que não existe: saída 2 e mensagem que diz o que fazer', (t) => {
  const { pasta } = repositorioDeTeste(t);

  const { status, stdout, stderr } = rodar(pasta, 'origin/nao-existe');
  assert.equal(status, 2);
  assert.equal(
    stderr.trim(),
    'Não consegui ler os commits de origin/nao-existe..HEAD. A referência existe? Tente "git fetch origin".',
  );
  assert.equal(stdout, '');
});

test('sem argumento: saída 2 e a linha de uso', (t) => {
  const { pasta } = repositorioDeTeste(t);

  const { status, stderr } = rodar(pasta);
  assert.equal(status, 2);
  assert.match(stderr, /^Uso: node tools\/verificar-commits\.mjs <base> \[<ponta>\]/);
});

test('modo --pr: título no padrão e descrição comum passam', () => {
  const { status, stdout } = rodarPr('feat: add tabs', 'O que entra\n\n- abas novas');
  assert.equal(status, 0);
  assert.match(stdout, /^1 mensagem\(ns\) conferida\(s\), 0 reprovada\(s\)\.$/m);
});

test('modo --pr: título fora do padrão ou descrição com coautoria reprovam', () => {
  const titulo = rodarPr('Add tabs');
  assert.equal(titulo.status, 1);
  assert.match(titulo.stderr, /^REPROVADO {2}título do PR: Add tabs$/m);

  const corpo = rodarPr('feat: add tabs', 'Texto.\n\nCo-Authored-By: Alguém <a@b.c>');
  assert.equal(corpo.status, 1);
  assert.match(corpo.stderr, /coautoria/);
});

test('modo --pr: sem título, saída 2', () => {
  const { status, stderr } = rodarPr('   ');
  assert.equal(status, 2);
  assert.match(stderr, /TITULO_PR está vazia/);
});
