import { test } from 'node:test';
import assert from 'node:assert/strict';
import { problemasDaMensagem, problemasDoAssunto } from '../../tools/verificar-commits.mjs';

test('assuntos no padrão são aceitos', () => {
  const bons = [
    'feat: add Rotinas, Habitos and Tarefas tabs',
    'fix(theme): keep the dark theme as default',
    'chore: add lint, formatting, unit tests and CI',
    'refactor(store)!: change the saved data format',
    'docs: add README',
  ];
  for (const assunto of bons) assert.deepEqual(problemasDoAssunto(assunto), [], assunto);
});

test('assuntos fora do padrão são reprovados', () => {
  const ruins = [
    'Add tabs', // sem tipo
    'feature: add tabs', // tipo que não existe
    'feat add tabs', // sem dois-pontos
    'feat:add tabs', // sem espaço depois dos dois-pontos
    'feat: ', // sem descrição
    'Feat: add tabs', // tipo com maiúscula
    'feat(Tema): add tabs', // escopo com maiúscula
    'feat: add tabs.', // ponto final
    `feat: ${'a'.repeat(80)}`, // longo demais
    '',
  ];
  for (const assunto of ruins) assert.notEqual(problemasDoAssunto(assunto).length, 0, assunto);
});

test('o limite de 72 caracteres é inclusivo', () => {
  assert.deepEqual(problemasDoAssunto(`feat: ${'a'.repeat(66)}`), []);
  assert.equal(problemasDoAssunto(`feat: ${'a'.repeat(67)}`).length, 1);
});

test('mensagem com coautoria ou "gerado por" é reprovada', () => {
  const corpos = [
    'Co-Authored-By: Alguém <a@b.c>',
    'co-authored-by: alguém <a@b.c>',
    'Signed-off-by: Alguém <a@b.c>',
    'Generated with uma ferramenta',
    '\u{1F916} texto',
  ];
  for (const corpo of corpos) {
    assert.equal(problemasDaMensagem(`feat: add tabs\n\n${corpo}`).length, 1, corpo);
  }
});

test('corpo comum não é reprovado', () => {
  const mensagem = 'feat: add tabs\n\nFirst working version.\nIt was generated by hand, with care.';
  assert.deepEqual(problemasDaMensagem(mensagem), []);
});
